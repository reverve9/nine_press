/* 열 폭 — 갈래 둘을 받는다. **한 배열에 섞지 않는다.**

     ① 몫   [1, 2, 1]                       균등 트랙 몇 개를 먹느냐
     ② 백분율 ["25%","30%","15%","30%"]      거터를 뺀 나머지의 % · 합 100

   몫은 골격의 열자리() 가 2:1 을 다루는 방식과 같다. 폭 [2,1,1] 이면 4트랙을 나눠
   첫 열이 둘을 먹는다.

   **둘은 같은 물건이 아니다.** 몫으로 묶은 열은 **안쪽 거터까지 제가 먹는다** —
   안폭 1002 · 4열에서 30% 를 몫 [5,6,3,6](20트랙)으로 흉내 내면 285.9px 이고
   백분율로 주면 282px 이다. 그래서 백분율은 몫의 대체가 아니라 **더 가는 자**다.

   파일 머리 규칙은 「가로 분할은 split() 하나」다. **백분율이 그 규칙을 여는 자리다** ·
   사용자 판정 · N-배경 b3. split() 은 균등 트랙만 내므로 임의 백분율을 못 낸다.
   여는 대신 split() 이 지키던 것을 그대로 지킨다 —
   첫 열은 x 0 · 열 사이는 거터 21 · **마지막 열이 나머지 px 을 받아** 오른쪽 끝에 딱 맞는다.

   세로는 "높이" 가 같은 어휘로 받는다 · 아래 §N-배경 b5. 다만 42 격자에 스냅되므로
   백분율이 4.76%p 단위로 끊긴다 — 세로에서 정확히 나누려면 몫을 쓴다. */

const 백분율 = /^(\d{1,3})%$/;

function 표열(폭, n, 표폭, i) {
  if (폭 == null) return split(0, 표폭, n, 표거터);
  if (!Array.isArray(폭) || 폭.length !== n) throw new Error(
    `자리 ${i} 의 표 "폭" 은 열 수(${n})와 같은 길이의 배열이어야 한다`);

  // ① 몫
  if (폭.every((v) => Number.isInteger(v))) {
    if (!폭.every((v) => v >= 1 && v <= 8)) throw new Error(
      `자리 ${i} 의 표 "폭" 을 몫으로 주면 1 ~ 8 사이 정수다 (받은 값 ${JSON.stringify(폭)})`);
    const 트랙 = split(0, 표폭, 폭.reduce((a, b) => a + b, 0), 표거터);
    const out = [];
    let k = 0;
    for (const w of 폭) {
      const a = 트랙[k], b = 트랙[k + w - 1];
      out.push({ x: a.x, w: b.x + b.w - a.x });
      k += w;
    }
    return out;
  }

  /* ② 백분율 — **마지막 열이 나머지를 다 받는다.**
     이 파일이 나머지를 다루는 규칙이 그것 하나다 · 사용자 판정 · N-배경 b4.
       split()  마지막 열이 end − x 를 받는다
       rows()   둘째 영역이 h − 걸음 을 받는다
     그래서 여기도 같다. **마지막 열에 적은 값은 안 읽는다** — 100 에서 앞을 뺀 것이
     마지막이다. 합이 99 든 101 이든 판은 어긋나지 않고 · 오른쪽 끝이 언제나 맞는다.
     막는 것은 하나뿐이다 · 앞 열들이 이미 100 을 넘겨 마지막에 남는 것이 없을 때. */
  if (폭.every((v) => typeof v === 'string' && 백분율.test(v))) {
    const 몫 = 폭.map((v) => Number(백분율.exec(v)[1]));
    const 앞 = 몫.slice(0, -1);
    if (!앞.every((v) => v >= 1 && v <= 99)) throw new Error(
      `자리 ${i} 의 표 "폭" 백분율은 1% ~ 99% 다 (받은 값 ${JSON.stringify(폭)})`);
    const 앞합 = 앞.reduce((a, b) => a + b, 0);
    if (앞합 > 99) throw new Error(
      `자리 ${i} 의 표 "폭" 은 마지막을 뺀 앞 열들 합이 ${앞합} 이다. ` +
      `마지막 열이 나머지를 받으므로 앞 열들 합은 99 이하여야 한다 (받은 값 ${JSON.stringify(폭)})`);
    몫[몫.length - 1] = 100 - 앞합;
    // 거터는 백분율 밖이다. 나눌 폭에서 먼저 뺀다 — 그래야 합 100 이 폭 전체를 덮는다
    const 남 = 표폭 - 표거터 * (n - 1);
    const out = [];
    let x = 0;
    몫.forEach((p, k) => {
      const w = k === n - 1 ? 표폭 - x : 반올림(남 * p / 100);
      out.push({ x, w });
      x += w + 표거터;
    });
    if (out.some((c) => c.w < 1)) throw new Error(
      `자리 ${i} 의 표 폭 ${JSON.stringify(폭)} 이 폭 ${표폭}px 에 안 들어간다. ` +
      `열을 줄이거나 작은 비율을 키운다`);
    return out;
  }

  throw new Error(
    `자리 ${i} 의 표 "폭" 은 몫 [1,2,1] 이거나 백분율 ["25%","75%"] 다. 한 배열에 섞지 않는다 ` +
    `(받은 값 ${JSON.stringify(폭)})`);
}

/* ─────────────────── §N-배경 b5 · 높이 · 세로 몫 ───────────────────
   **가로가 「폭」이면 세로는 「높이」다.** 열쇠 이름도 값 갈래도 같다 · N-배경 b7.
   「채움」은 열쇠가 아니라 **높이에 주는 값**이다 — 그래야 둘이 한 쌍으로 읽힌다.

     없음                            칸마다 한 줄 42 · 자리를 안 채운다
     "높이": "채움"                   칸이 고르게 나눠 갖는다
     "높이": [1, 2, 1]               몫 · 칸마다 몇 몫이냐
     "높이": ["25%","30%","45%"]     백분율 · 마지막이 나머지를 받는다 (가로와 같다)
     "높이": [1, 1, 1, {"공백": 1}]   공백 · 칸이 아닌 빈 자리 · 칸 수에 안 든다

   **세로는 가로와 성질이 다르다 — 42 격자에 갇힌다.** 자리에 남은 높이가 909 면
   쓸 수 있는 것은 42 × 21 칸뿐이고 **한 칸이 4.76%p** 다. 그래서 백분율을 적어도
   그 언저리 42 배수로 앉는다. 정확히 셋으로 나누려면 백분율 말고 몫 [1,1,1] 을 쓴다.

   **남는 블록은 「공백」이 받는다.** 공백이 없으면 지금까지처럼 위아래로 가른다.
   가로의 「마지막이 받는다」를 그대로 옮기면 마지막 행만 84px 두꺼워져 표가 기운다 —
   세로의 나머지는 반올림 부스러기가 아니라 **42 덩어리**라서 그렇다 · 실측 · 사용자 판정.
   그래서 세로에서 나머지를 받는 자리는 공백이다. 공백이 여럿이면 **마지막 공백**이 받는다. */

const 공백몫 = (v) => (v !== null && typeof v === 'object' && !Array.isArray(v) ? v.공백 : null);

function 높이나누기(높이, 칸수, 남은, i) {
  const T = Math.floor(남은 / 42);
  if (T < 칸수) throw new Error(
    `자리 ${i} 의 표가 자리를 채우는데 칸 ${칸수}개가 들어갈 높이가 없다 ` +
    `(남은 높이 ${남은} · 칸마다 42 는 있어야 한다)`);

  let 슬롯;
  if (높이 === '채움') {
    슬롯 = Array.from({ length: 칸수 }, () => ({ 공백: false, 값: 1 }));
  } else {
    if (!Array.isArray(높이) || !높이.length) throw new Error(
      `자리 ${i} 의 표 "높이" 는 "채움" 이거나 몫 배열이다 (받은 값 ${JSON.stringify(높이)})`);
    슬롯 = 높이.map((v) => {
      const g = 공백몫(v);
      return g == null ? { 공백: false, 값: v } : { 공백: true, 값: g };
    });
    const 칸슬롯 = 슬롯.filter((s) => !s.공백).length;
    if (칸슬롯 !== 칸수) throw new Error(
      `자리 ${i} 의 표 "높이" 에 칸이 ${칸슬롯}개다. 칸 수 ${칸수} 와 맞춘다 ` +
      `(공백은 칸 수에 안 든다 · 머리행도 한 칸이다)`);
  }

  /* 갈래 — 몫이냐 백분율이냐. **섞지 않는다.** 공백도 그 배열의 갈래를 따른다 */
  const 값 = 슬롯.map((s) => s.값);
  let 몫, 전체;
  if (값.every((v) => Number.isInteger(v))) {
    if (!값.every((v, k) => v >= (슬롯[k].공백 ? 0 : 1) && v <= 20)) throw new Error(
      `자리 ${i} 의 표 "높이" 몫은 1 ~ 20 사이 정수다 (공백은 0 도 된다 · 받은 값 ${JSON.stringify(높이)})`);
    몫 = 값;
    전체 = 값.reduce((a, b) => a + b, 0);
  } else if (값.every((v) => typeof v === 'string' && 백분율.test(v))) {
    const p = 값.map((v) => Number(백분율.exec(v)[1]));
    const 앞 = p.slice(0, -1);
    if (!앞.every((v) => v >= 0 && v <= 99)) throw new Error(
      `자리 ${i} 의 표 "높이" 백분율은 0% ~ 99% 다 (받은 값 ${JSON.stringify(높이)})`);
    /* 앞 칸들 합은 **100 까지** 받는다 — 가로(99 이하)와 다른 자리다.
       세로에서는 끝에 공백을 두는 것이 정상 쓰임이고 그때 칸들 합이 딱 100 이다.
       마지막이 0 이 되어도 칸은 아래에서 한 블록(42)을 보장받고 · 공백은 0 이어도 된다.
       그래서 가로처럼 99 로 막으면 「칸 100% + 끝 공백」이 못 쓰인다 · 실측으로 잡았다. */
    const 앞합 = 앞.reduce((a, b) => a + b, 0);
    if (앞합 > 100) throw new Error(
      `자리 ${i} 의 표 "높이" 는 마지막을 뺀 앞 칸들 합이 ${앞합} 이다. ` +
      `마지막이 나머지를 받으므로 앞 칸들 합은 100 이하여야 한다 (받은 값 ${JSON.stringify(높이)})`);
    p[p.length - 1] = 100 - 앞합;
    몫 = p;
    전체 = 100;
  } else {
    throw new Error(
      `자리 ${i} 의 표 "높이" 는 몫 [1,2,1] 이거나 백분율 ["30%","70%"] 다. 한 배열에 섞지 않는다 ` +
      `(받은 값 ${JSON.stringify(높이)})`);
  }

  // 칸은 적어도 한 블록(42) 을 갖는다. 공백은 0 이어도 된다
  const 블록 = 몫.map((w, k) =>
    Math.max(슬롯[k].공백 ? 0 : 1, Math.floor(T * w / 전체)));
  const 합 = 블록.reduce((a, b) => a + b, 0);
  if (합 > T) throw new Error(
    `자리 ${i} 의 표 "높이" ${JSON.stringify(높이)} 가 남은 높이 ${남은}px 에 안 들어간다 ` +
    `(42 × ${T} 칸을 쓸 수 있는데 ${합} 칸이 필요하다)`);

  // 남는 블록 — 마지막 공백이 받는다. 공백이 없으면 위아래로 가른다
  let 위로 = 0;
  const 남는 = T - 합;
  if (남는) {
    const 끝공백 = 슬롯.map((s, k) => (s.공백 ? k : -1)).filter((k) => k >= 0).pop();
    if (끝공백 != null) 블록[끝공백] += 남는;
    else 위로 = Math.floor(남는 / 2) * 42;
  }
  return { 슬롯: 슬롯.map((s, k) => ({ 공백: s.공백, h: 블록[k] * 42 })), 위로 };
}

function 표그리기(t, i, 안폭, 남은, P, 겉) {
  if (typeof t !== 'object' || Array.isArray(t)) throw new Error(
    `자리 ${i} 의 "표" 는 객체여야 한다`);
  if (!Array.isArray(t.행) || !t.행.length) throw new Error(
    `자리 ${i} 의 표에 "행" 배열이 없다`);
  if (t.머리 != null && !Array.isArray(t.머리)) throw new Error(
    `자리 ${i} 의 표 "머리" 는 배열이어야 한다`);

  const n = t.머리?.length ?? t.행[0].length;
  for (const [j, 행] of t.행.entries()) {
    if (!Array.isArray(행)) throw new Error(`자리 ${i} 의 표 ${j + 1}행이 배열이 아니다`);
    if (행.length !== n) throw new Error(
      `자리 ${i} 의 표 ${j + 1}행이 ${행.length}칸이다. 열 수 ${n} 과 맞춘다`);
  }

  const 선 = t.선 ?? '가로';
  if (!Object.prototype.hasOwnProperty.call(표선갈래, 선)) throw new Error(
    `자리 ${i} 의 표 "선" 값 ${JSON.stringify(선)} 을 모른다. ` +
    `쓸 수 있는 값은 ${Object.keys(표선갈래).join(' · ')} 뿐이다`);
  const 축 = 표선갈래[선];

  const 열 = 표열(t.폭, n, 안폭, i);
  const 칸수 = t.행.length + (t.머리 ? 1 : 0);

  /* 칸 높이 — 기본은 한 줄 42 다. "높이" 가 있으면 높이나누기() 가 정한다.
     배치[k] 는 k번째 칸의 { y, h } 다 · 공백은 여기 안 들어온다 — 자리만 먹는다. */
  const 배치 = [];
  let 위로 = 0, 총높이 = 42 * 칸수;
  if (t.채움 != null) throw new Error(
    `자리 ${i} 의 표가 옛 열쇠 "채움" 을 쓴다. 가로가 "폭" 이면 세로는 "높이" 다 · ` +
    `고르게 채우려면 "높이": "채움" 으로 적는다`);
  if (t.높이) {
    const r = 높이나누기(t.높이, 칸수, 남은, i);
    위로 = r.위로;
    let y = 0;
    for (const s of r.슬롯) { if (!s.공백) 배치.push({ y, h: s.h }); y += s.h; }
    총높이 = y;
  } else {
    for (let k = 0; k < 칸수; k++) 배치.push({ y: k * 42, h: 42 });
  }

  /* 칠 — 셀 배경. **도형과 같은 색 어휘를 쓴다.** 새 색을 만들지 않는다.
     글자 밑에 깔리는 사각형이라 글줄 자리에 개입하지 않는다 · 설계 §4-2.
       "칠": { "머리": "블록배경", "행": [null, "#FDF6EC"] }
     행 배열은 짧아도 된다 — 없는 자리는 안 칠한다. */
  const 칠 = t.칠 ?? {};
  if (typeof 칠 !== 'object' || Array.isArray(칠)) throw new Error(
    `자리 ${i} 의 표 "칠" 은 객체여야 한다`);
  if (칠.행 != null && !Array.isArray(칠.행)) throw new Error(
    `자리 ${i} 의 표 "칠.행" 은 배열이어야 한다`);
  const 머리칠 = 색(칠.머리, 배경이름, '칠.머리', i, '표');
  const 행칠 = (칠.행 ?? []).map((v, j) => 색(v, 배경이름, `칠.행[${j}]`, i, '표'));

  const 칸 = [];
  const 줄 = [];
  const 바탕 = [];
  const 칠하기 = (c, y, h) => {
    if (!c) return;
    바탕.push(`<div class="tf" style="left:0;top:${y}px;width:${안폭}px;` +
      `height:${h}px;background:${c}"></div>`);
  };
  const 셀 = (글, 경로, x, w, y, h, 머리) =>
    `<div class="tc${머리 ? ' th' : ''}" style="left:${x}px;top:${y}px;width:${w}px;height:${h}px"` +
    `${dp(경로)}>${inline(글)}</div>`;

  let k = 0;
  if (t.머리) {
    const { y, h } = 배치[k++];
    칠하기(머리칠, y, h);
    t.머리.forEach((글, c) => 칸.push(셀(글, [...P, '표', '머리', c], 열[c].x, 열[c].w, y, h, true)));
  }
  t.행.forEach((행, ri) => {
    const { y, h } = 배치[k++];
    칠하기(행칠[ri], y, h);
    행.forEach((글, c) => 칸.push(셀(글, [...P, '표', '행', ri, c], 열[c].x, 열[c].w, y, h, false)));
  });

  /* 가로선 — **칸 사이에만.** 표 위와 아래에는 안 긋는다.
     공백이 끼어 두 칸이 안 붙어 있으면 그 사이에는 선이 없다 —
     선은 맞닿은 두 칸을 가르는 것이지 빈 자리를 가르는 것이 아니다.
     그래서 공백은 「여기서 표를 끊는다」는 뜻도 된다. */
  if (축.includes('x')) {
    for (let j = 1; j < 칸수; j++) {
      const 위칸 = 배치[j - 1], 아래칸 = 배치[j];
      if (위칸.y + 위칸.h !== 아래칸.y) continue;
      const 굵 = t.머리 && j === 1;   // 머리행 아래만 진하게
      줄.push(`<div class="tl${굵 ? ' hd' : ''}" ` +
        `style="left:0;top:${아래칸.y}px;width:${안폭}px;height:1px"></div>`);
    }
  }
  // 세로선 — 열 사이 거터 한가운데. 첫 칸 위에서 마지막 칸 아래까지 · 공백까지 안 내려간다
  if (축.includes('y')) {
    const 위 = 배치[0].y;
    const 아래 = 배치[칸수 - 1].y + 배치[칸수 - 1].h;
    for (let j = 1; j < 열.length; j++) {
      const x = 열[j - 1].x + 열[j - 1].w + Math.floor((표거터 - 1) / 2);
      줄.push(`<div class="tl" style="left:${x}px;top:${위}px;width:1px;height:${아래 - 위}px"></div>`);
    }
  }

  /* 위 여백 — **인라인 margin-top 은 클래스가 주는 위계 간격을 덮어쓴다.**
     그래서 「위로」(공백이 위에 남은 만큼)를 적을 때는 겉이 정한 간격을 같이 실어야 한다.
     안 그러면 그 간격이 통째로 사라져 표가 42px 위로 올라앉는다 · 실측 05면 top 126 → 84.
     기준선.mjs 는 84 도 126 도 42 배수라 이걸 못 잡는다 · scripts/자리재기.mjs 가 잡는다.
     인라인을 쓸 때는 간격 클래스를 g0 으로 바꿔 둘이 겹치지 않게 한다. */
  return `<div class="tb ${위로 ? 'g0' : 겉.클래스}" style="height:${총높이}px` +
    (위로 ? `;margin-top:${겉.간격 + 위로}px` : '') + 겉.스타일 +
    `"${겉.표식 ?? ''}>${바탕.join('')}${줄.join('')}${칸.join('')}</div>`;
}

/* ─────────────────── §N-자유 b · 단계띠 폐기 ───────────────────
   **단계띠를 걷어냈다** · 사용자 판정. 칸마다 라벨 + 내용이 세로로 앉고 · 칠과 현재칠과
   반전이 따로 놀아 열쇠가 여덟이었다. 실물에서 쓰는 자리는 몇 안 되는데
   렌더러 · 도크 · 관문이 셋 다 그만큼 무거워졌다.

   **대신 자리를 비워 넘긴다.** 요소 「비움」이 그 자리를 42 배수로 잡아 두고
   출력에는 아무것도 안 낸다 · 키노트가 그 좌표 위에 그린다 · 아래 §N-자유 c.
   옛 문안의 `단계띠` 는 던진다 — 조용히 사라지면 판이 빈 채로 나간다.

   `rules/page.css` 의 `.sp` 규칙은 그대로 남았다(이 파일은 끝에만 덧붙인다).
   아무도 안 부르는 죽은 규칙이다 · 다음에 규칙을 통째로 손볼 때 걷는다. */

/* ─────────────────── §N-그림 · 그림 ───────────────────
   **그림은 배경이 아니다.** 도형 · 표 · 칠은 글자 밑에 깔리지만 그림은 제 자리를 먹는다.
   그래서 세로 격자에 걸린다 — 높이가 42 의 배수가 아니면 아래 글줄이 통째로 밀린다.
   설계 §4-3 · §4-4 · 세로는 스냅 · 가로는 자유.

   **배관은 이 파일 밖에 이미 다 깔려 있다.** 여기서는 `src="assets/…"` 를 그대로 낸다.
     app/ui/Shell.jsx     `src="assets/` → `/api/img/`      개발 화면
     scripts/build.js     --link 면 상대경로 · 아니면 base64  산출 HTML · PDF
   그러니 경로는 **레포 기준 `assets/` 로 시작하는 상대경로**여야 한다. 절대경로 · http ·
   data: 를 받으면 저 둘이 못 바꿔 개발 화면이나 산출본 한쪽에서 그림이 깨진다. 막는다.

     "그림": "assets/캡처/D1_구조도.svg"          짧은 꼴 · 경로만 · 나머지는 기본값
     "그림": { "경로": …, "높이": …, "맞춤": …, "설명": … }

   높이 — 가로가 「폭」이면 세로는 「높이」다. 표와 같은 어휘를 쓴다 · §N-배경 b5.
     "채움"(기본)   앞뒤에 놓인 것을 빼고 남은 높이를 다 먹는다 · 42 배수로 내림
     12            **블록 수**다. 42 × 12 = 504px.
                   표의 정수는 칸끼리 나누는 「몫」이지만 그림은 하나뿐이라 나눌 상대가 없다
     "50%"         남은 높이의 백분율 · 가장 가까운 42 배수

   맞춤 — 그림에는 제 비율이 있고 자리에는 제 치수가 있다. 둘이 안 맞을 때 무엇을 버리나.
     "전체"(기본)   그림이 다 보인다 · 남는 쪽에 여백이 생긴다      object-fit:contain
     "채우기"       칸을 꽉 채운다 · 넘치는 쪽이 잘린다             object-fit:cover
   늘리기(fill)는 안 연다 — 비율을 망가뜨리는 것은 어떤 문안도 원한 적이 없다.

   설명 — alt 다. 그림이 안 뜰 때 남는 글이고 · 읽어 주는 기계가 읽는 것이다. */

const 그림확장 = /\.(png|jpe?g|svg|webp|gif)$/i;
const 맞춤이름 = { 전체: 'contain', 채우기: 'cover' };

function 그림경로(v, i) {
  if (typeof v !== 'string' || 빔(v)) throw new Error(
    `자리 ${i} 의 그림 "경로" 가 없다. 레포 기준 상대경로를 적는다 (예 "assets/캡처/D1_구조도.svg")`);
  const p = v.trim();
  if (!p.startsWith('assets/') || p.includes('..') || /["'<>\s]/.test(p)) throw new Error(
    `자리 ${i} 의 그림 "경로" ${JSON.stringify(v)} 을 못 쓴다. ` +
    `"assets/" 로 시작하는 레포 기준 상대경로여야 하고 · 따옴표 · 공백 · ".." 를 못 넣는다 ` +
    `(개발 화면과 산출본이 이 경로를 각자 바꿔 문다)`);
  if (!그림확장.test(p)) throw new Error(
    `자리 ${i} 의 그림 "경로" ${JSON.stringify(v)} 의 형식을 모른다. ` +
    `png · jpg · svg · webp · gif 만 된다`);
  return p;
}

/* 블록 수 — 남은 높이 T 블록 안에서 몇을 먹느냐. 적어도 하나(42)는 갖는다 */
function 그림블록(높이, T, i) {
  /* 블록 수로 못박은 그림은 **남은 높이를 안 본다.** 그러니 T 를 먼저 따지면 안 된다 —
     같은 자리에 채움류가 없으면 T 가 0 으로 들어오고 · 멀쩡한 그림이 던진다 */
  if (Number.isInteger(높이)) {
    if (높이 < 1 || 높이 > 30) throw new Error(
      `자리 ${i} 의 그림 "높이" 를 수로 주면 1 ~ 30 사이 블록 수다 · 한 블록이 42px 이다 ` +
      `(받은 값 ${JSON.stringify(높이)})`);
    return 높이;
  }
  if (T < 1) throw new Error(
    `자리 ${i} 의 그림이 들어갈 높이가 없다 (앞뒤에 놓인 것을 빼고 42 가 안 남았다)`);
  if (높이 == null || 높이 === '채움') return T;
  if (typeof 높이 === 'string' && 백분율.test(높이)) {
    const p = Number(백분율.exec(높이)[1]);
    if (p < 1 || p > 100) throw new Error(
      `자리 ${i} 의 그림 "높이" 백분율은 1% ~ 100% 다 (받은 값 ${JSON.stringify(높이)})`);
    return Math.max(1, 반올림(T * p / 100));
  }
  throw new Error(
    `자리 ${i} 의 그림 "높이" 는 "채움" 이거나 블록 수 12 이거나 백분율 "50%" 다 ` +
    `(받은 값 ${JSON.stringify(높이)})`);
}

function 그림그리기(그림, i, 남은, 겉) {
  const g = typeof 그림 === 'string' ? { 경로: 그림 } : 그림;
  if (typeof g !== 'object' || Array.isArray(g)) throw new Error(
    `자리 ${i} 의 "그림" 은 경로 문자열이거나 객체여야 한다`);

  const 경로 = 그림경로(g.경로, i);
  const 맞춤 = g.맞춤 ?? '전체';
  if (!Object.prototype.hasOwnProperty.call(맞춤이름, 맞춤)) throw new Error(
    `자리 ${i} 의 그림 "맞춤" 값 ${JSON.stringify(g.맞춤)} 을 모른다. ` +
    `쓸 수 있는 값은 ${Object.keys(맞춤이름).join(' · ')} 뿐이다`);

  const h = 그림블록(g.높이, Math.floor(남은 / 42), i) * 42;

  /* **인라인 margin-top 을 안 쓴다** · §N-배경 b 가 표에서 물린 함정이다.
     위 간격은 겉이 준 클래스 하나가 맡는다 · rules/page.css ㉜. */
  return `<div class="im ${겉.클래스}" style="height:${h}px${겉.스타일}"${겉.표식 ?? ''}>` +
    `<img src="${경로}" alt="${esc(g.설명 ?? '')}" style="object-fit:${맞춤이름[맞춤]}">` +
    `</div>`;
}

/* ─────────────────── §N-자유 · 자리 안은 배열이다 ───────────────────
   **자리가 열쇠 뭉치에서 요소 배열로 바뀌었다.**

     옛   자리 { 제목 · 요약 · 문단[] · 표 · 그림 · 출처 }      순서 고정 · 하나씩만
     새   자리 { 내용: [ {제목} · {문단} · {그림} · {문단} ] }   순서 자유 · 중복 자유

   못 하던 셋이 열린다 · 「문단 → 그림 → 문단」 · 표 둘 · 요소마다 제 도형.

   **옛 꼴도 그대로 읽는다.** `내용` 이 없으면 옛 열쇠를 고정 순서로 접어 같은 배열을 만든다.
   접힌 요소는 **옛 표식 경로를 그대로 쓴다** — 그래야 옛 문안의 `roundtrip` 이 안 깨지고
   회귀 기준 여덟 문안을 안 고쳐도 된다. 두 꼴을 같이 쓰면 던진다.

   요소 하나는 **내용 열쇠 하나 + 도형(선택)** 이다. 둘을 넣으면 순서가 다시 애매해진다. */

const 내용열쇠 = ['제목', '요약', '문단', '목록', '번호목록', '표', '수치', '그림', '출처', '여백', '비움'];
const 머리열쇠 = new Set(['제목', '요약']);
/* **자리와 요소가 이름을 나눠 쓰는 열쇠 둘.** 뜻이 다르다 · 겹침 검사에서 뺀다.
     여백  자리 = 안쪽 패딩          요소 = 42 덩이 빈 칸
     비움  자리 = 자리를 통째로 넘김   요소 = 그 높이만 넘김 */
const 자리겹침 = new Set(['여백', '비움']);
// 배경을 주면 글자를 좌우로 들인다. 세로는 안 건드린다 — 격자가 깨진다 · 설계 §4-4
const 글자요소 = new Set(['제목', '요약', '문단', '목록', '번호목록', '출처']);
const 요소좌우 = 21;

/* 자리 → [{ 요소, 열쇠, 경로 }] · 경로(뒤…) 가 표식 경로를 만든다 */
function 내용읽기(자리, i, P) {
  if (자리.내용 != null) {
    if (!Array.isArray(자리.내용)) throw new Error(
      `자리 ${i} 의 "내용" 은 배열이어야 한다`);
    const 옛것 = 내용열쇠.filter((k) => !자리겹침.has(k) && 자리[k] != null);
    if (옛것.length) throw new Error(
      `자리 ${i} 가 "내용" 배열과 옛 열쇠 ${옛것.join(' · ')} 를 같이 쓴다. ` +
      `한 꼴로 적는다 — 옛 열쇠를 "내용" 안으로 옮긴다`);
    return 자리.내용.map((요소, j) => {
      if (요소 == null || typeof 요소 !== 'object' || Array.isArray(요소)) throw new Error(
        `자리 ${i} · 내용 ${j} 가 객체가 아니다. { "문단": "…" } 같은 꼴로 적는다`);
      const 있는것 = 내용열쇠.filter((k) => 요소[k] != null);
      if (있는것.length !== 1) throw new Error(
        `자리 ${i} · 내용 ${j} 에 내용 열쇠가 ${있는것.length}개다(${있는것.join(' · ') || '없다'}). ` +
        `요소 하나는 내용 열쇠 하나다 — 둘을 넣으려면 요소를 둘로 나눈다. ` +
        `쓸 수 있는 열쇠는 ${내용열쇠.join(' · ')}`);
      return { 요소, 열쇠: 있는것[0], 경로: (...뒤) => [...P, '내용', j, ...뒤] };
    });
  }

  if (자리.단계띠 != null) throw new Error(
    `자리 ${i} 가 폐기한 열쇠 "단계띠" 를 쓴다 · N-자유 b. ` +
    `칸마다 라벨 + 내용이 앉는 띠는 앱이 안 그린다 — 그 높이를 { "비움": [n, "단계띠"] } 로 ` +
    `남겨 두고 키노트에서 그린다`);

  /* 옛 꼴 · 고정 순서로 접는다. **경로에 열쇠를 굽지 않는다** —
     표 · 단계띠는 제 안에서 열쇠를 다시 붙이므로(`[...P, '표', '머리', c]`)
     여기서 미리 넣으면 `표.표.머리` 로 두 번 들어간다. 접두만 준다. */
  const out = [];
  const 옛경로 = (...뒤) => [...P, ...뒤];
  const 넣기 = (열쇠, 값, 경로 = 옛경로) => out.push({ 요소: { [열쇠]: 값 }, 열쇠, 경로 });
  if (자리.제목) 넣기('제목', 자리.제목);
  if (자리.요약) 넣기('요약', 자리.요약);
  /* 문단은 짧은 꼴(문자열 하나)도 받는다. **그때 표식에 번호를 안 붙인다** —
     `["문단",0]` 을 주면 편집기가 문자열의 첫 글자에 쓰려 들어 문안이 깨진다.
     `roundtrip` 이 잡았다 · 그 전까지 옛 문안 여럿이 이 상태로 있었다.
     문단은 잎사귀가 저 하나라 경로가 인자를 안 읽는다. */
  if (자리.문단 != null) {
    const 배열 = Array.isArray(자리.문단);
    (배열 ? 자리.문단 : [자리.문단]).forEach((t, j) => {
      if (빔(t)) return;
      넣기('문단', t, 배열 ? () => [...P, '문단', j] : 옛경로);
    });
  }
  for (const 열쇠 of ['목록', '번호목록', '표', '수치', '그림']) {
    if (자리[열쇠] == null) continue;
    넣기(열쇠, 자리[열쇠]);
  }
  if (자리.출처) 넣기('출처', 자리.출처);
  return out;
}

/* ─────────────────── 위계 간격 ───────────────────
   **렌더러가 정하고 클래스로 준다.** 옛 CSS 는 `.bt + .bd` 꼴 조합표였는데
   요소가 임의 순서로 오면 그 표가 폭발한다(일곱 갈래면 49줄). 그리고 조합표는
   **인라인 margin 에 언제나 진다** — 표가 그 함정을 이미 한 번 밟았다.
   그래서 여기서 계산해 `g0 · gh · gb` 셋 중 하나를 붙이고
   `rules/page.css ㉝` 이 그 셋만 읽는다. 옛 조합표는 특정도가 같고 앞에 있어 진다.

   쓸 수 있는 값은 0 과 42 뿐이다 · 21 은 문단마다 홀짝으로 엇갈린다 · v8 §9 ⑧.

     0    첫 요소 · 여백 앞뒤 · 출처 앞 · 제목 뒤의 요약(머리는 한 덩이다)
     gh   머리(제목 · 요약) 끝에서 몸으로 넘어갈 때 · --머리뒤
     gb   그 밖 · --문단사이

   옛 문안이 그대로 통과하는 것이 이 규칙이 맞다는 증거다 · §4 관문. */
function 간격정하기(요소들) {
  return 요소들.map((e, j) => {
    if (j === 0) return { 클래스: 'g0', 간격: 0 };
    const 앞 = 요소들[j - 1].열쇠;
    if (e.열쇠 === '여백' || 앞 === '여백') return { 클래스: 'g0', 간격: 0 };
    if (e.열쇠 === '출처') return { 클래스: 'g0', 간격: 0 };
    if (앞 === '제목' && e.열쇠 === '요약') return { 클래스: 'g0', 간격: 0 };
    if (머리열쇠.has(앞) && !머리열쇠.has(e.열쇠)) return { 클래스: 'gh', 간격: 42 };
    return { 클래스: 'gb', 간격: 42 };
  });
}

/* 42 덩이 수 — 여백 · 비움이 같은 규칙을 쓴다 */
function 블록수(n, 열쇠, i, j) {
  if (!Number.isInteger(n) || n < 1 || n > 30) throw new Error(
    `자리 ${i} · 내용 ${j} 의 "${열쇠}" 는 1 ~ 30 사이 블록 수다 · 한 블록이 42px 이다 ` +
    `(받은 값 ${JSON.stringify(n)})`);
  return n;
}

/* 비움 값 — 짧은 꼴은 높이만 · 긴 꼴은 [높이, 무엇으로 채울지] */
const 비움값 = (v) => (Array.isArray(v) ? [v[0], v[1] ?? ''] : [v, '']);

/* ─────────────────── 확정 높이 ───────────────────
   「채움」을 쓰는 요소가 남은 높이를 알려면 **나머지 전부의 높이를 미리 알아야 한다.**

   확정   제목 · 요약 · 출처 42 · 여백 42×n · 수치 84(+라벨 42) ·
          표(높이 없으면 42×칸수) · 그림(블록 수로 준 것)
   불확정 문단 · 목록 · 번호목록 — **줄 수가 글자에 달렸다.**
          브라우저 없이 못 센다. 어림해서 격자를 깨뜨리느니 안 된다고 말한다.

   배열이 되며 이 판정이 넓어졌다 — 옛 코드는 「앞이 제목 · 요약뿐일 때만」 이라는
   자리 하나짜리 관문이었고 · 지금은 요소마다 물어 순서와 무관하게 센다. */
function 확정높이(요소, 열쇠, i, j) {
  switch (열쇠) {
    case '제목': case '요약': case '출처':
      return 42;
    case '여백':
      return 블록수(요소.여백, '여백', i, j) * 42;
    case '비움':
      return 블록수(비움값(요소.비움)[0], '비움', i, j) * 42;
    case '수치': {
      const v = 요소.수치;
      if (!Array.isArray(v)) return null;
      const 라벨 = v.some((c) => Array.isArray(c) && !빔(c[2]));
      return 84 + (라벨 ? 42 : 0);
    }
    case '표': {
      const t = 요소.표;
      if (t?.높이) return null;                       // 채움류 — 남은 높이를 먹는다
      if (!Array.isArray(t?.행)) return null;
      return 42 * (t.행.length + (t.머리 ? 1 : 0));
    }
    case '그림': {
      const g = typeof 요소.그림 === 'string' ? {} : (요소.그림 ?? {});
      return Number.isInteger(g.높이) ? g.높이 * 42 : null;   // 채움 · 백분율은 채움류
    }
    default:
      return null;                                    // 문단 · 목록 · 번호목록
  }
}

// 남은 높이를 먹는 요소인가 · 자리에 하나만 둘 수 있다
const 채움류 = (요소, 열쇠) => (열쇠 === '표' && !!요소.표?.높이) ||
  (열쇠 === '그림' && !Number.isInteger((typeof 요소.그림 === 'string' ? {} : 요소.그림 ?? {}).높이));

/* ─────────────────── 블록 · 자리 하나 ─────────────────── */

function 블록(자리, r, i, 여백문서) {
  const pad = 자리.여백 ?? 여백문서;
  // 좌표 뒤에 도형을 이어 붙인다 · 순서 고정 · 도형이 없으면 좌표만 나온다
  const st = `left:${r.x}px;top:${r.y}px;width:${r.w}px;height:${r.h}px` +
    (pad !== 여백기본 || 자리.여백 != null ? `;padding:${pad}px` : '') + 도형(자리, i);
  const P = ['자리', i];
  // 글자 반전은 명시로만 켠다 — 밝기를 계산해 자동 판정하면 작성자가 결과를 못 읽는다
  if (자리.도형?.글자 != null && 자리.도형.글자 !== '반전') throw new Error(
    `자리 ${i} 의 도형 "글자" 값 ${JSON.stringify(자리.도형.글자)} 을 모른다. ` +
    `쓸 수 있는 값은 "반전" 뿐이다`);
  // 자리 번호는 도구 모드에서만 붙인다 — 편집기가 자리를 고르는 근거다. 출력에는 없다
  const o = [`<div class="bx" style="${st}"` +
    (자리.도형?.글자 === '반전' ? ` data-글자="반전"` : '') + dk(자리.이름) +
    (도구 ? ` data-자리="${i}"` : '') + `>`];

  if (자리.라벨 != null) throw new Error(
    `자리 ${i} 가 옛 열쇠 "라벨" 을 쓴다. 박스 타이틀이면 "제목" · 출처 표기면 "출처" 로 바꾼다`);

  /* 비워 두는 자리 — 키노트 · 파워포인트에서 채운다.
     판이 2339 × 1654 로 키노트 슬라이드와 같은 좌표계라 이 좌표를 그대로 쓸 수 있다.

     **출력에는 아무것도 안 나간다.** 표식은 도구 모드(편집기)에서만 그린다.
     그래야 산출 HTML · PDF 가 진짜로 비어 그 위에 덮어쓸 수 있다.
     좌표는 `node scripts/비움.mjs <문안>` 으로 표를 뽑는다. */
  if (자리.비움) {
    // 도형도 못 산다 — 비움은 「출력에 아무것도 안 나간다」가 계약이다 · 설계 §5-11
    const 있는것 = [...내용열쇠.filter((k) => !자리겹침.has(k)), '내용', '도형']
      .filter((k) => 자리[k] != null);
    if (있는것.length) throw new Error(
      `자리 ${i} 가 "비움" 인데 ${있는것.join(' · ')} 를 갖고 있다. 비울 거면 내용을 지운다`);
    if (도구) o.push(
      `<div class="emp"><span>${inline(typeof 자리.비움 === 'string' ? 자리.비움 : '비움')}</span>` +
      `<i>x ${r.x} · y ${r.y} · ${r.w} × ${r.h}</i></div>`);
    o.push('</div>');
    return o.join('');
  }

  const 요소들 = 내용읽기(자리, i, P);
  const 간격들 = 간격정하기(요소들);
  const 안폭 = r.w - pad * 2;
  const 안높이 = r.h - pad * 2;

  /* 채움류가 먹을 남은 높이 — 나머지 요소의 확정 높이와 간격을 다 빼고 남은 것이다.
     하나라도 불확정이면 못 잰다 · 그 이름을 대고 던진다. */
  const 채움자리 = 요소들.findIndex((e) => 채움류(e.요소, e.열쇠));
  if (요소들.filter((e) => 채움류(e.요소, e.열쇠)).length > 1) throw new Error(
    `자리 ${i} 에 남은 높이를 먹는 요소가 둘 이상이다(표 "높이" · 그림 "채움"). ` +
    `한 자리에 하나만 둔다 — 하나를 블록 수로 못박거나 다른 자리로 옮긴다`);

  let 남은 = 0;
  if (채움자리 >= 0) {
    const 못센것 = [];
    let 쓴것 = 0;
    요소들.forEach((e, j) => {
      쓴것 += 간격들[j].간격;
      if (j === 채움자리) return;
      const h = 확정높이(e.요소, e.열쇠, i, j);
      if (h == null) 못센것.push(e.열쇠);
      else 쓴것 += h;
    });
    if (못센것.length) throw new Error(
      `자리 ${i} 에서 ${요소들[채움자리].열쇠} 가 남은 높이를 먹는데 같은 자리에 ` +
      `${[...new Set(못센것)].join(' · ')} 가 있다. 줄 수가 글자에 달려 미리 못 센다. ` +
      `그 요소를 다른 자리로 옮기거나 · 높이를 블록 수로 못박는다`);
    남은 = 안높이 - 쓴것;
  }

  요소들.forEach((e, j) => {
    const 겉 = { ...간격들[j], 스타일: 요소도형(e.요소, e.열쇠, i, j) };
    o.push(요소그리기(e, i, j, 안폭, 남은, 겉));
  });

  /* 「+」 — **박스 안에서 놓는다** · 사용자 판정 · N-자유 c.
     도크에서 놓으면 「어느 박스에?」가 늘 흐렸다. 박스마다 제 「+」를 두면
     누른 그 박스가 곧 놓을 자리라 흐릴 것이 없다.
     빈 자리면 자리를 통째로 덮고 · 내용이 있으면 오른쪽 아래 구석에 작게 붙는다.
     도구 모드에서만 나온다 · 산출 HTML · PDF 에는 없다. */
  if (도구) {
    if (o.length === 1) o.push(
      `<div class="emp warn add"><span>+</span><i>눌러서 내용을 놓는다 · 일부러 비울 거면 "비움"</i></div>`);
    else o.push(`<div class="plus" title="여기에 놓는다">+</div>`);
  }
  o.push('</div>');
  return o.join('');
}

/* 요소 도형 — **자리 도형과 같은 어휘 · 같은 함정.** 테두리를 border 로 안 그린다.
   글자 요소에만 좌우 21 을 들인다 · 세로는 0 이다 — 단계띠에서 배운 그대로다.
   표는 칸이 절대 배치라 좌우 패딩을 주면 안폭 계산과 어긋나 오른쪽으로 넘친다. */
function 요소도형(요소, 열쇠, i, j) {
  if (요소.도형 == null) return '';
  // 글자 반전은 명시로만 켠다 — 자리 도형과 같은 규칙이다 · §N-배경 a1
  if (요소.도형.글자 != null && 요소.도형.글자 !== '반전') throw new Error(
    `자리 ${i} · 내용 ${j} 의 도형 "글자" 값 ${JSON.stringify(요소.도형.글자)} 을 모른다. ` +
    `쓸 수 있는 값은 "반전" 뿐이다`);
  const s = 도형(요소, `${i} · 내용 ${j}`);
  if (!s) return '';
  return s + (글자요소.has(열쇠) ? `;padding:0 ${요소좌우}px` : '');
}

/* ─────────────────── 요소 하나 ─────────────────── */

function 요소그리기({ 요소, 열쇠, 경로 }, i, j, 안폭, 남은, 겉) {
  const 반전 = 요소.도형?.글자 === '반전' ? ` data-글자="반전"` : '';
  // 요소 번호는 도구 모드에서만 붙인다 — 편집기가 요소를 고르는 근거다. 출력에는 없다
  const 표식 = (도구 ? ` data-요소="${j}"` : '') + 반전;
  겉.표식 = 표식;
  const 덩이 = (cls, 속) =>
    `<div class="${cls} ${겉.클래스}"${겉.스타일 ? ` style="${겉.스타일.slice(1)}"` : ''}` +
    `${표식}${dp(경로(열쇠))}>${속}</div>`;

  switch (열쇠) {
    case '제목': return 덩이('bt', inline(요소.제목));
    case '요약': return 덩이('sm', inline(요소.요약));
    case '문단': return 빔(요소.문단) ? '' : 덩이('bd', inline(요소.문단));
    case '출처': return 덩이('lb', inline(요소.출처));

    // 여백 — 조판상의 틈이다. 도구에서도 안 보인다
    case '여백':
      return `<div class="sx ${겉.클래스}" style="height:${블록수(요소.여백, '여백', i, j) * 42}px"${표식}></div>`;

    /* 비움 — **앱이 못 하는 것을 키노트로 넘긴다** · 설계 §5-11 의 요소판이다.
       자리 「비움」이 자리를 통째로 넘겼다면 이건 **그 높이만** 넘긴다.
       그래서 한 자리를 반은 앱이 · 반은 키노트가 맡을 수 있다 · N-자유 c.

       **출력에는 아무것도 안 나간다.** 표식은 도구 모드에서만 그린다 —
       그래야 산출 HTML · PDF 가 진짜로 비어 그 위에 덮어쓸 수 있다.
       좌표는 `node scripts/비움.mjs <문안>` 이 표로 뽑는다. */
    case '비움': {
      const [n, 무엇] = 비움값(요소.비움);
      const h = 블록수(n, '비움', i, j) * 42;
      if (!도구) return `<div class="sx ${겉.클래스}" style="height:${h}px"${표식}></div>`;
      return `<div class="sk ${겉.클래스}" style="height:${h}px"${표식}>` +
        `<span>${inline(빔(무엇) ? '비움' : 무엇)}</span><i>${n} × 42 = ${h}px</i></div>`;
    }

    // 목록 — 항목 하나가 편집 잎사귀 하나다. data-p 는 li 에 붙는다
    case '목록': case '번호목록': {
      const [태그, cls] = 열쇠 === '목록' ? ['ul', 'ls'] : ['ol', 'ol'];
      if (!Array.isArray(요소[열쇠])) throw new Error(`자리 ${i} 의 "${열쇠}" 는 배열이어야 한다`);
      // 빈 항목은 안 낸다 — 글자는 지웠는데 마커만 남는 유령 항목을 만들지 않는다.
      // 인덱스는 원본 그대로 쓴다. 다시 매기면 data-p 가 배열과 어긋난다
      const 항목 = 요소[열쇠]
        .map((t, k) => (빔(t) ? '' : `<li${dp(경로(열쇠, k))}>${inline(t)}</li>`))
        .join('');
      if (!항목) return '';
      return `<${태그} class="${cls} ${겉.클래스}"` +
        `${겉.스타일 ? ` style="${겉.스타일.slice(1)}"` : ''}${표식}>${항목}</${태그}>`;
    }

    case '표':
      return 표그리기(요소.표, i, 안폭, 남은, 경로(), 겉);

    // 수치 — 값(강조 수치 52) + 단위 한 줄 84 · 그 아래 라벨 42 → 한 칸 126
    case '수치': {
      if (!Array.isArray(요소.수치)) throw new Error(`자리 ${i} 의 "수치" 는 배열이어야 한다`);
      const 칸 = 요소.수치.map((c, k) => {
        const [값, 단위, 라벨] = Array.isArray(c) ? c : [c, '', ''];
        if (빔(값)) return '';
        return `<div class="n"><div class="nv">` +
          `<span class="val"${dp(경로('수치', k, 0))}>${inline(값)}</span>` +
          (빔(단위) ? '' : `<span class="unit"${dp(경로('수치', k, 1))}>${inline(단위)}</span>`) +
          `</div>` +
          (빔(라벨) ? '' : `<div class="nk"${dp(경로('수치', k, 2))}>${inline(라벨)}</div>`) +
          `</div>`;
      }).join('');
      if (!칸) return '';
      return `<div class="nm ${겉.클래스}"` +
        `${겉.스타일 ? ` style="${겉.스타일.slice(1)}"` : ''}${표식}>${칸}</div>`;
    }

    case '그림':
      return 그림그리기(요소.그림, i, 남은, 겉);

    default:
      throw new Error(`자리 ${i} · 내용 ${j} 의 열쇠 "${열쇠}" 를 모른다`);
  }
}

/* ─────────────────── 면 ─────────────────── */

export function renderPage(page, doc = {}) {
  const 모드 = page.모드 === '연속' ? '연속' : '카피';
  const 여백문서 = doc.여백 ?? 여백기본;
  const rects = 영역(page);
  const 자리 = page.자리 ?? [];

  if (자리.length !== rects.length) {
    throw new Error(
      `면 ${page.번호 ?? '?'} · 골격 ${page.골격 ?? '구성'} 은 영역 ${rects.length} 개를 만드는데 ` +
      `자리는 ${자리.length} 개다. 개수를 맞춘다`);
  }

  const 카피 = 모드 === '카피' && page.카피
    ? `<div class="cp">` +
      (page.카피.메인 ? `<b class="cpm"${dp(['카피', '메인'])}>${inline(page.카피.메인)}</b>` : '') +
      (page.카피.서브 ? `<span class="cps"${dp(['카피', '서브'])}>${inline(page.카피.서브)}</span>` : '') +
      `</div>`
    : '';

  return `<div class="sheet"><div class="page" data-mode="${모드}">
<div class="hd"${dp(['제목'])}>${inline(page.제목)}</div>
${카피}
<div class="tt"${dp(['논지'])}>${inline(page.논지)}</div>
${rects.map((r, i) => 블록(자리[i], r, i, 여백문서)).join('\n')}
<div class="ft"><span class="fn">${inline(page.번호)}</span><span class="fd">${inline(doc.문서명 ?? '')}</span></div>
</div></div>`;
}

/* ─────────────────── §N-배경 a2 · doc.판면 폐기 ───────────────────
   `doc.판면` 은 아무 문자열이나 `.wrap` 에 꽂던 통로였다. 없앤다 · N2 §1-3.

   **N2 의 「구분선」은 안 넣는다** · 사용자 판정. 자리 테두리로 그리면
   거터 양쪽에 선이 둘 생기고 이웃 없는 바깥쪽에도 선이 그어져서 잘못이고 ·
   거터 한가운데 한 줄로 고쳐 그려 봐도 **개념이 골격에 묶여 있다.**
   선은 골격과 무관하게 **판에 얹는 요소**여야 한다 — 도형 · 그림과 같은 층이다.
   그래서 「선 얹기」로 다시 세운다 · 다음 페이즈 · 설계 §8.

   검사용 외곽선(`.dbg`)은 그대로 산다. 편집기 [블록] 토글이 켜고 · 문안에 안 남는다. */

/* ─────────────────── 문서 ───────────────────
   css 를 주면 <style> 로 박는다 — 산출 HTML 이 자기완결이 되어
   파일을 옮기든 메일로 보내든 판면이 깨지지 않는다. 이것이 기본이다.
   css 를 안 주면 <link> 로 건다 (규칙을 고치며 새로고침하는 개발용).

   기준선 자는 render(doc,{기준선:true}) 또는 doc.기준선 으로 켠다 → .wrap.bl */

export function render(doc, { css, cssBase = '../../rules', 도구: 표식 = false, 기준선 = false } = {}) {
  if (doc.판면 != null) throw new Error(
    `문서가 옛 열쇠 "판면" 을 쓴다. 검사용 외곽선은 편집기 [블록] 토글로 옮겼다 · ` +
    `문안에 남는 열쇠가 아니다`);
  도구 = 표식;
  let pages;
  try {
    pages = (doc.면 ?? []).map((p) => renderPage(p, doc)).join('\n');
  } finally {
    도구 = false;
  }
  const head = css
    ? `<style>\n${css}\n</style>`
    : `<link rel="stylesheet" href="${cssBase}/fonts.css">\n` +
      `<link rel="stylesheet" href="${cssBase}/page.css">`;
  return `<!DOCTYPE html><html lang="ko"><head><meta charset="utf-8">
<title>${doc.문서명 ?? 'nine_press'}</title>
${head}
</head><body><div class="wrap${기준선 || doc.기준선 ? ' bl' : ''}">
${pages}
</div></body></html>`;
}

