def 목록(*xs, 위여백=None):
    d = {"목록": list(xs)}
    if 위여백 is not None: d["위여백"] = 위여백
    return d
def 번호목록(*xs, 위여백=None):
    d = {"번호목록": list(xs)}
    if 위여백 is not None: d["위여백"] = 위여백
    return d
def 문단(s, 위여백=None):
    d = {"문단": s}
    if 위여백 is not None: d["위여백"] = 위여백
    return d
def 표(열, 머리, 행, 밀도="cp", 위여백=None):
    t = {"밀도": 밀도, "열": 열, "머리": 머리, "행": 행}
    d = {"표": t}
    if 위여백 is not None: d["위여백"] = 위여백
    return d
def 블록(라벨, *내용, 배경=None, 채움=None):
    b = {"라벨": 라벨}
    if 배경: b["배경"] = 배경
    if 채움 is not None: b["채움"] = 채움
    b["내용"] = list(내용)
    return b
def 열(*블록들, 폭=1):
    return {"폭": 폭, "블록": list(블록들)}
def 행(*열들):
    return {"열": list(열들)}

